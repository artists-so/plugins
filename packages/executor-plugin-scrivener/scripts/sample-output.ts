/**
 * Render `docs/tool-output.md` — what each tool actually answers with.
 *
 *   bun run samples            rewrite the document
 *   bun run samples --stdout   print it instead
 *
 * Every response is produced by calling the real tool handlers — the same entry
 * point the Executor runtime calls — against the synthetic fixture in
 * `test/fixture.ts`. Generated documentation cannot describe a response the
 * plugin stopped giving, and CI fails if the committed document is not what a
 * fresh render produces.
 *
 * Uuids and temporary paths are elided so that a re-render is a clean diff.
 */

import { Effect } from '@executor-js/sdk/core';
import { mkdtemp, rm, writeFile } from 'fs/promises';
import { tmpdir } from 'os';
import { join } from 'path';
import { scrivenerPlugin } from '../src/server.js';
import { createFixtureProject } from '../test/fixture.js';

interface ToolLike {
	readonly name: string;
	readonly handler: (input: { args: unknown; ctx: unknown; elicit: unknown }) => unknown;
}

const tools =
	(
		scrivenerPlugin as unknown as () => { staticIntegrations: () => { tools: ToolLike[] }[] }
	)().staticIntegrations()[0]?.tools ?? [];

const workspace = await mkdtemp(join(tmpdir(), 'scriv-sample-'));
const path = await createFixtureProject(workspace);

const UUID = /[0-9A-F]{8}-[0-9A-F]{4}-[0-9A-F]{4}-[0-9A-F]{4}-[0-9A-F]{12}/gi;

const out: string[] = [];
const say = (text = ''): void => {
	out.push(text);
};

/** Elide what changes per run, so re-rendering is a clean diff. */
const stable = (text: string): string =>
	text
		.split(path)
		.join('/path/to/Novel.scriv')
		.split(workspace)
		.join('/tmp')
		.replace(UUID, '<uuid>');

const call = async (name: string, args: Record<string, unknown>): Promise<unknown> => {
	const target = tools.find((candidate) => candidate.name === name);
	if (target === undefined) throw new Error(`No tool named ${name}`);
	return Effect.runPromise(
		target.handler({ args: { path, ...args }, ctx: {}, elicit: undefined }) as Effect.Effect<
			unknown,
			unknown
		>
	);
};

const OUTLINE = [
	{
		title: 'Act I',
		type: 'Folder',
		children: [
			{
				title: 'The arrival',
				type: 'Text',
				label: 'DAWN',
				status: 'DRAFTED',
				synopsis: 'He wakes before the alarm he did not set.',
				content: 'The first line.\n\nThe second, after a break.',
			},
			{ title: 'The lockout', type: 'Text', label: 'DAY', status: 'PLANNED' },
		],
	},
];

const show = async (label: string, name: string, args: Record<string, unknown>): Promise<void> => {
	const shown = JSON.stringify(args)
		.replace(JSON.stringify(OUTLINE), 'OUTLINE')
		.replace(/"(\w+)":/g, '$1: ')
		.replace(/,(?=\S)/g, ', ')
		.replace(/^\{|\}$/g, '')
		.trim();
	say(`### ${label}`);
	say();
	say('```ts');
	say(`await tools.scrivener_native.${name}({ ${'path' in args ? '' : 'path, '}${stable(shown)} });`);
	say('```');
	say();
	say('```json');
	say(stable(JSON.stringify(await call(name, args), null, 2)));
	say('```');
	say();
};

say('# What the tools answer with');
say();
say('Generated by `bun run samples` against the synthetic fixture in `test/fixture.ts`,');
say('through the same handlers the Executor runtime calls. Do not edit by hand.');
say();
say('Uuids and paths are elided. The fixture defines the labels `DAWN` and `DAY` and');
say('the statuses `PLANNED` and `DRAFTED`; a real project defines its own.');
say();
say('The outline referred to below as `OUTLINE`:');
say();
say('```ts');
say(`const OUTLINE = ${JSON.stringify(OUTLINE, null, 2)};`);
say('```');
say();

// force: true on the writes, because the machine rendering these samples may
// well have Scrivener open on something else — the last sample shows the
// refusal that appears when it does.
await show('Reading a project: its shape, and the vocabularies it defines', 'binder_read', {
	as: 'text',
});
await show('Planning a write — a dry run reports and touches nothing', 'binder_sync', {
	outline: OUTLINE,
	dryRun: true,
});
await show('Applying the same call', 'binder_sync', { outline: OUTLINE, force: true });
await show('Running it a second time — the point of a declarative outline', 'binder_sync', {
	outline: OUTLINE,
	force: true,
});

const tree = (await call('binder_read', {})) as {
	binder: { children?: { title: string; children?: { id: string; title: string }[] }[] }[];
};
const id =
	tree.binder[0]?.children
		?.find((child) => child.title === 'Act I')
		?.children?.find((child) => child.title === 'The arrival')?.id ?? '';

await show('Reading a document back', 'document_read', { id });

say('## Refusals');
say();
say('A refusal arrives as **data** — `{ refused, message }`, and nothing that could be');
say('mistaken for a result. A thrown error would reach the caller as an opaque');
say('`Internal tool error [<id>]` with the reason left behind in the daemon log, which');
say('is no use to whoever has to decide what to do next. Check for `refused` before');
say('reading a result.');
say();

await show('An id the binder does not contain', 'document_read', {
	id: 'FFFFFFFF-FFFF-4FFF-8FFF-FFFFFFFFFFFF',
});
await show('A label the project does not define', 'binder_sync', {
	outline: [{ title: 'Bad', label: 'DUSK' }],
	force: true,
});
await show('A path that is not a Scrivener project', 'binder_read', {
	path: join(workspace, 'Not-a-project.scriv'),
});

// A lock file is the deterministic half of the open-in-Scrivener guard; the
// other half is `pgrep`, which cannot be staged from a script.
await writeFile(join(path, 'Files', 'user.lock'), 'machine: elsewhere\n', 'utf8');
await show('The project is open somewhere else (here: a lock file)', 'document_write', {
	id,
	synopsis: 'Rewritten while the project was open.',
});

await rm(workspace, { recursive: true, force: true });

const document = `${out.join('\n').replace(/\n{3,}/g, '\n\n').trim()}\n`;
if (process.argv.includes('--stdout')) {
	console.log(document);
} else {
	const target = join(import.meta.dir, '..', 'docs', 'tool-output.md');
	await writeFile(target, document, 'utf8');
	console.log(`wrote ${target}`);
}
